#!/usr/bin/env python3
"""Build the main highest-variation table from the saved Table S11 data."""

import csv
from pathlib import Path
from copn_analysis.private_io import private_input, private_output


POLICIES = tuple(f"A{i}" for i in range(6))
CLASSES = ("PD", "AP", "HC")


def read_rows(source):
    with private_input(source).open(newline="") as stream:
        rows = [
            row for row in csv.DictReader(stream)
            if row["group"] == "Q5" and row["budget"] in ("3", "4")
        ]
    expected = {(budget, policy) for budget in ("3", "4") for policy in POLICIES}
    assert len(rows) == 12
    assert {(r["budget"], r["method_id"]) for r in rows} == expected
    assert all(r["display_group"] == "Highest variation" for r in rows)
    for budget in ("3", "4"):
        selected = [r for r in rows if r["budget"] == budget]
        shared = ("prediction_records", "unique_participants", "n_PD", "n_AP", "n_HC")
        assert len({tuple(r[field] for field in shared) for r in selected}) == 1
        for row in selected:
            n = int(row["prediction_records"])
            assert sum(int(row[f"n_{c}"]) for c in CLASSES) == n
            assert abs(float(row["mean_set_size"]) - int(row["set_size_sum"]) / n) < 1e-12
            assert abs(float(row["full_set_rate"]) - int(row["full_set_count"]) / n) < 1e-12
            for c in CLASSES:
                assert abs(float(row[f"core_coverage_{c}"])
                           - int(row[f"core_covered_{c}"]) / int(row[f"n_{c}"])) < 1e-12
    return rows


def build(source: Path, output: Path):
    output = private_output(output)
    rows = read_rows(source)
    text = [
        "% Generated by tables/build_highest_variation_table.py from saved Table S11 data.",
        r"\begin{table}[htbp]",
        r"\caption{\textbf{Prediction policies in the highest variation group.} "
        r"Highest variation means the roughly 20\% of held-out records with the "
        r"largest Scenario Sensitivity Index (SSI) scores, above the 80th percentile "
        r"at each budget. SSI measures variation in the possible diagnoses returned "
        r"across the 21 scenarios. Cutoffs were calculated separately for J3 and J4, "
        r"and records with equal scores stayed together.}\label{tab:highest-variation}",
        r"\centering",
        r"\tablebodyfont",
        r"\setlength{\tabcolsep}{4pt}",
        r"\renewcommand{\arraystretch}{1.15}",
        r"\setlength{\TableWidth}{\dimexpr\linewidth-10\tabcolsep\relax}",
        r"\begin{tabular}{@{}"
        r">{\raggedright\arraybackslash}p{0.11\TableWidth}"
        r">{\raggedleft\arraybackslash}p{0.17\TableWidth}"
        r">{\raggedleft\arraybackslash}p{0.18\TableWidth}"
        r">{\raggedleft\arraybackslash}p{0.18\TableWidth}"
        r">{\raggedleft\arraybackslash}p{0.18\TableWidth}"
        r">{\raggedleft\arraybackslash}p{0.18\TableWidth}@{}}",
        r"\toprule",
        r"\textbf{Policy} & \textbf{Average labels returned} & "
        r"\textbf{All three labels (\%)} & \textbf{PD included (\%)} & "
        r"\textbf{AP included (\%)} & \textbf{HC included (\%)} \\",
        r"\midrule",
    ]
    for budget in ("3", "4"):
        selected = {r["method_id"]: r for r in rows if r["budget"] == budget}
        first = selected["A0"]
        title = (
            "A. Primary assessment budget J3 (levels 1--3)" if budget == "3"
            else "B. Expanded assessment budget J4 (levels 1--4)"
        )
        text.append(
            r"\multicolumn{6}{@{}p{\linewidth}@{}}{\textbf{" + title + r"}} \\"
        )
        counts = (
            f"{int(first['prediction_records']):,} records from "
            f"{int(first['unique_participants']):,} participants; class record counts: "
            + "; ".join(f"{c}: {int(first[f'n_{c}']):,}" for c in CLASSES)
        )
        text.append(r"\multicolumn{6}{@{}p{\linewidth}@{}}{" + counts + r"} \\")
        text.append(r"\addlinespace[3pt]")
        for policy in POLICIES:
            r = selected[policy]
            cells = [
                policy,
                f"{float(r['mean_set_size']):.3f}",
                f"{100 * float(r['full_set_rate']):.2f}",
                *(f"{100 * float(r[f'core_coverage_{c}']):.2f}" for c in CLASSES),
            ]
            text.append(" & ".join(cells) + r" \\")
        if budget == "3":
            text.extend([r"\addlinespace[3pt]", r"\midrule"])
    text.extend([
        r"\bottomrule",
        r"\end{tabular}",
        r"\par\medskip",
        r"\begin{minipage}{\linewidth}",
        r"\singlespacing\tablefootnotefont\raggedright",
        r"PD, Parkinson's disease; AP, atypical Parkinsonian category; "
        r"HC, healthy control. Class percentages count records whose returned "
        r"set includes their recorded category. For the one-label rule A0, this "
        r"is the percentage correctly classified within that class. "
        r"The same records were used for all six policies within each budget; "
        r"a participant can contribute records in more than one repeat.",
        r"\par\smallskip",
        r"A0 and A1 use only the primary ensemble: 60\% CatBoost (M2) and 40\% "
        r"hierarchical model (M4) predictions. A2--A5 also use 20 additional "
        r"analyses from the adaptive elastic-net model (M5) under different "
        r"assumptions about missing data. A2 combines scenario-specific sets; "
        r"A3 combines scores; A4 can add labels to A3 using estimated error "
        r"risk; A5 can then add labels using study-defined costs. These are "
        r"descriptive estimates without uncertainty intervals. "
        r"\SupplementHighlight{Supplement S7, Table S11, panels A--B} reports "
        r"all five variation groups.",
        r"\end{minipage}",
        r"\end{table}",
    ])
    output.write_text("\n".join(text) + "\n")
    print(f"Built {output.name}: 12 budget-policy rows from the highest variation group.")


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    build(args.source, args.output)
